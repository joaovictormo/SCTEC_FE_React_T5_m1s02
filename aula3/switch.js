let diaSemanaNum = 0;

switch (diaSemanaNum) {
    case 1:
        console.log("Hoje é domingo!");
        break;
    case 2:
        console.log("Hoje é segunda!");
        break;
    case 3:
        console.log("Hoje é terça!");
        break;
    case 4:
        console.log("Hoje é quarta!");
        break;
    case 5:
        console.log("Hoje é quinta!");
        break;
    case 6:
        console.log("Hoje é sexta!");
        break;
    case 7:
        console.log("Hoje é sábado!");
        break;
    default:
        console.log("Insira um valor entre 1 e 7");
}

console.log("Fora do switch, segue a execução...");
